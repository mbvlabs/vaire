func TestCopyGuardSettingsHandoffRequiresEffectivePermanentProof(t *testing.T) {
	hist := catalog.Extension{Name: "hist", CopySafety: catalog.CopySafetyDisabled,
		CopySettings: map[string]string{"hist.worker": "off"}}
	// The desired map says off, but the actual operator configuration at
	// higher precedence says on: releasing the guard would unsuppress.
	got, err := CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist}, Current: []catalog.Extension{hist},
		Permanent:        map[string]string{"hist.worker": "off"},
		HandoffPermanent: map[string]string{"hist.worker": "on"},
		CopyDB:           "app", Pending: false,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Settings["hist.worker"] != "off" || got.Handoff != nil {
		t.Fatalf("unproven higher-precedence value released the guard: %+v", got)
	}
	// A decoded literal "'off'" is not equivalent to off; it must not be
	// normalized a second time into a handoff.
	got, err = CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist}, Current: []catalog.Extension{hist},
		Permanent:        map[string]string{"hist.worker": "off"},
		HandoffPermanent: map[string]string{"hist.worker": "'off'"},
		CopyDB:           "app", Pending: false,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Settings["hist.worker"] != "off" || got.Handoff != nil {
		t.Fatalf("a decoded quoted literal was normalized twice: %+v", got)
	}
	got, err = CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist}, Current: []catalog.Extension{hist},
		Permanent:        map[string]string{"hist.worker": "off"},
		HandoffPermanent: map[string]string{"hist.worker": "off"},
		CopyDB:           "app", Pending: false,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Settings != nil || got.Handoff["hist.worker"] != "off" {
		t.Fatalf("proven equivalent value did not hand off: %+v", got)
	}
	// A fresh pending copy ignores an old handoff and re-establishes off.
	got, err = CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist}, Current: []catalog.Extension{hist},
		Permanent:        map[string]string{"hist.worker": "on"},
		HandoffPermanent: map[string]string{"hist.worker": "on"},
		Handoff:          map[string]string{"hist.worker": "off"},
		CopyDB:           "app", Pending: true,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Settings["hist.worker"] != "off" || got.Handoff != nil {
		t.Fatalf("a pending copy inherited an old handoff: %+v", got)
	}
}

