func TestCopyGuardSettingsHistoricalOnlySurvivesAndHandsOff(t *testing.T) {
	hist := catalog.Extension{Name: "hist", Settings: map[string]string{"hist.mode": "on"},
		CopySafety: catalog.CopySafetyDisabled, CopySettings: map[string]string{"hist.worker": "off"}}
	current := catalog.Extension{Name: "cur", Settings: map[string]string{"cur.mode": "on"}}
	// A same-database restore later apply: the historical-only mandatory
	// suppression stays because the permanent configuration does not supply it.
	got, err := CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist, current}, Current: []catalog.Extension{current},
		Permanent: map[string]string{"cur.mode": "on"}, CopyDB: "app", Pending: false,
	})
	if err != nil {
		t.Fatal(err)
	}
	if got.Settings["hist.mode"] != "on" || got.Settings["hist.worker"] != "off" {
		t.Fatalf("guard settings = %v", got.Settings)
	}
	if _, ok := got.Settings["cur.mode"]; ok {
		t.Fatalf("permanent setting was duplicated in the guard: %v", got.Settings)
	}
	// The operator supplies the equivalent permanent value: the guard hands
	// the key off and records it.
	handed, err := CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist, current}, Current: []catalog.Extension{current},
		Permanent: map[string]string{"cur.mode": "on", "hist.worker": "off"},
		Explicit:  map[string]string{"hist.worker": "off"}, CopyDB: "app", Pending: false,
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := handed.Settings["hist.worker"]; ok || handed.Handoff["hist.worker"] != "off" {
		t.Fatalf("equivalent permanent suppression did not hand off: %+v", handed)
	}
	// A deliberate later change is respected: the recorded handoff keeps the
	// guard from reconstructing the old suppression.
	later, err := CopyGuardSettings(CopyGuardSettingsOptions{
		Known: []catalog.Extension{hist, current}, Current: []catalog.Extension{current},
		Permanent: map[string]string{"cur.mode": "on", "hist.worker": "on"},
		Explicit:  map[string]string{"hist.worker": "on"}, CopyDB: "app", Pending: false,
		Handoff: handed.Handoff,
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := later.Settings["hist.worker"]; ok {
		t.Fatalf("a deliberate later change was overridden: %+v", later.Settings)
	}
	if later.Handoff["hist.worker"] != "off" {
		t.Fatalf("handoff provenance was lost: %+v", later.Handoff)
	}
}

