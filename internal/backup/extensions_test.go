func TestConfigLexerDecodesPostgresValues(t *testing.T) {
	cases := []struct {
		line  string
		name  string
		value string
		ok    bool
	}{
		{"x = 'off''suffix'", "x", "off'suffix", true},
		{"x = '''off'''", "x", "'off'", true},
		{`x = 'off\''`, "x", "off'", true},
		{"x = 'of#f' # comment", "x", "of#f", true},
		{"x = ' off '", "x", " off ", true},
		{"X off", "x", "off", true},
		{"UPPER.CASE = on # trailing", "upper.case", "on", true},
		{"x = 'off' extra", "", "", false},
		{"x = 'unterminated", "", "", false},
		{`x = 'bad\q'`, "", "", false},
		{"x =", "", "", false},
	}
	for _, c := range cases {
		tok, ok, err := lexConfigLine(c.line)
		if ok != c.ok {
			t.Errorf("%q ok = %v, want %v (%v)", c.line, ok, c.ok, err)
			continue
		}
		if !c.ok {
			if err == nil {
				t.Errorf("%q was accepted", c.line)
			}
			continue
		}
		if tok.Name != c.name || tok.Value != c.value {
			t.Errorf("%q = %q/%q, want %q/%q", c.line, tok.Name, tok.Value, c.name, c.value)
		}
	}
}

