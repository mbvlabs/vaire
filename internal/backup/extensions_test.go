func TestCopyGuardWinsAndSurvivesRecoveryCleanup(t *testing.T) {
	oldWrite := writeCopyGuardFile
	writeCopyGuardFile = func(path string, data []byte, perm os.FileMode) error {
		return os.WriteFile(path, data, perm) //nolint:gosec // G304: test-owned path
	}
	t.Cleanup(func() { writeCopyGuardFile = oldWrite })
	dir := t.TempDir()
	raw := "# Do not edit this file manually!\n" +
		"shared_preload_libraries = 'copied'\n" +
		"# Recovery settings generated by pgBackRest restore on 2026-11-10\n" +
		"restore_command = 'archive-get'\n"
	if err := os.WriteFile(filepath.Join(dir, "postgresql.auto.conf"), []byte(raw), 0o600); err != nil {
		t.Fatal(err)
	}
	guard := CopyGuard{Preloads: []string{"copied", "retained"}, Settings: map[string]string{"cron.launch_active_jobs": "off"}}
	if _, err := InstallCopyGuard(dir, guard); err != nil {
		t.Fatal(err)
	}
	got, present, err := ReadCopyGuard(dir)
	if err != nil || !present || !slices.Equal(got.Preloads, []string{"copied", "retained"}) ||
		got.Settings["cron.launch_active_jobs"] != "off" {
		t.Fatalf("guard = %+v, %v, %v", got, present, err)
	}
	if _, err := InstallCopyGuard(dir, guard); err != nil {
		t.Fatal(err)
	}
	conf, _ := os.ReadFile(filepath.Join(dir, "postgresql.auto.conf")) //nolint:gosec // test file
	if strings.Count(string(conf), copyGuardBegin) != 1 {
		t.Fatalf("guard duplicated:\n%s", conf)
	}
	kept, dropped := withoutRecoverySettings(string(conf))
	if !strings.Contains(kept, copyGuardBegin) || !slices.Contains(dropped, "restore_command") {
		t.Fatalf("promote cleanup dropped the guard or kept recovery settings: %q %v", kept, dropped)
	}
	if err := repointAutoConf(dir, "/old/path"); err != nil {
		t.Fatal(err)
	}
	if _, present, _ := ReadCopyGuard(dir); !present {
		t.Fatal("a path rewrite dropped the guard")
	}
	if _, err := RemoveCopyGuard(dir); err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(filepath.Join(dir, "postgresql.auto.conf")) //nolint:gosec // test file
	if strings.Contains(string(after), copyGuardBegin) || strings.Contains(string(after), "cron.launch_active_jobs") {
		t.Fatalf("guard removal left managed lines:\n%s", after)
	}
	// The plain assignment beneath the guard is the operator's provenance:
	// it wins again when the guard is deliberately released.
	if !strings.Contains(string(after), "shared_preload_libraries = 'copied'") {
		t.Fatalf("guard removal lost the underlying plain assignment:\n%s", after)
	}
}

