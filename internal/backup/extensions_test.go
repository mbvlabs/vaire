func TestPruneForRestoreRetiresActivationAuthorityAndKeepsHistory(t *testing.T) {
	r, _ := decode(nil)
	r.RecordExtensionRequirements("old-abc123", "old", []catalog.Extension{ext("pg_trgm")}, time.Now())
	r.Activation["old"] = ActivationFence{OperationID: "op-1", Kind: "fork", Database: "old", Instance: "old-instance", Phase: "adopted"}
	r.AwaitingRecovery["old"] = Awaiting{Stanza: "old-abc123", Since: "2026-01-01T00:00:00Z"}
	raw, err := json.Marshal(r)
	if err != nil {
		t.Fatal(err)
	}
	out, pruned, err := PruneForRestore(raw, []AwaitingDatabase{{Name: "old", Stanza: "old-abc123"}}, time.Now())
	if err != nil {
		t.Fatal(err)
	}
	got, err := decode(out)
	if err != nil {
		t.Fatal(err)
	}
	if len(got.Activation) != 0 {
		t.Fatalf("a rebuilt host inherited lost-host activation authority: %+v", got.Activation)
	}
	if _, ok := got.ExtensionRequirementsFor("old-abc123"); !ok {
		t.Fatal("the rebuild dropped retained extension history")
	}
	if !got.IsAwaiting("old") {
		t.Fatal("the rebuild dropped the awaiting recovery record")
	}
	got.Activation["old"] = ActivationFence{
		OperationID: "op-new", Kind: "restore-promote", Database: "old", Instance: "new-instance",
		TargetStanza: "old-abc123", OldStanza: "old-abc123", NewStanza: "old-abc123", Phase: "prepared",
	}
	if got.Activation["old"].Instance != "new-instance" {
		t.Fatal("the new-instance model could not establish its own authority")
	}
	if _, ok := got.ExtensionRequirementsFor("old-abc123"); !ok {
		t.Fatal("the new-instance model lost retained history")
	}
	found := false
	for _, p := range pruned {
		if p.Kind == "activation_fence" && p.Database == "old" {
			found = true
		}
	}
	if !found {
		t.Fatalf("the pruned activation fence was not reported: %+v", pruned)
	}
}

